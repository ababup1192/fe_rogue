#!/usr/bin/env python3
"""agents-pack をゲームに配る (make sync-agents の本体)。

配布物一覧の正本は agents-pack/manifest.json。この解釈器と Studio (NewGame.flix) の
解釈器は manifest を読むだけで、リストを二重に持たない。AGENTS.md は
共通指針 AGENTS.core.md + スキル一覧 (frontmatter から自動生成。Claude 以外の
エージェントも AGENTS.md だけで skills に気づけるように) + ゲームの AGENTS.local.md を
連結して生成し、CLAUDE.md は @AGENTS.md の 1 行にする。冪等。

  python3 bin/sync-agents.py --game /path/to/game --version 0.23.4
  python3 bin/sync-agents.py --check-manifest   # manifest が正しい JSON で src が全実在するか

標準ライブラリだけで動く (Windows / macOS / Linux 共通)。
"""

import argparse
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "agents-pack" / "manifest.json"
SKILLS_DIR = ROOT / "agents-pack" / "skills"


def load_manifest():
    with open(MANIFEST, encoding="utf-8") as fh:
        m = json.load(fh)
    for key in ("copy", "copyIfAbsent", "copyDirs"):
        if not isinstance(m.get(key), list):
            raise ValueError(f"manifest に {key} 配列がありません")
        for e in m[key]:
            if not isinstance(e, dict) or "src" not in e or "dst" not in e:
                raise ValueError(f"{key} の要素に src / dst がありません: {e}")
    return m


def check_manifest():
    """正しい JSON か・src が全実在するかだけを見る (check-docs-sync が呼ぶ)。"""
    try:
        m = load_manifest()
    except (OSError, ValueError, json.JSONDecodeError) as e:
        print(f"[sync-agents] NG: agents-pack/manifest.json が読めません: {e}",
              file=sys.stderr)
        return 1
    bad = 0
    for key in ("copy", "copyIfAbsent", "copyDirs"):
        for e in m[key]:
            if not (ROOT / e["src"]).exists():
                print(f"[sync-agents] NG: manifest の {key} が指す {e['src']} が"
                      " engine に実在しません", file=sys.stderr)
                bad = 1
    return bad


def read_text_lf(path):
    """改行をいじらずに読む。text モードだと Windows で CRLF 変換がかかり、
    Studio (Flix 版) の LF 直書きとバイト一致しなくなる。"""
    return path.read_bytes().decode("utf-8")


def write_text_lf(path, text):
    """LF のまま書く (Windows の既定は CRLF に化ける)。"""
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def skill_description(skill_md):
    """frontmatter の description: の 1 行目 (囲みの \" は外す) を返す。
    SKILL.md が無い skill は Flix 版と同じく空文字に倒す。"""
    try:
        lines = read_text_lf(skill_md).splitlines()
    except OSError:
        return ""
    for line in lines:
        if line.startswith("description:"):
            desc = line[len("description:"):].strip()
            if desc.startswith('"'):
                desc = desc[1:]
            if desc.endswith('"'):
                desc = desc[:-1]
            return desc
    return ""


def build_agents_md(game, version):
    parts = [
        f"<!-- generated by flix_game_engine agents-pack (engine v{version})."
        " 編集しないで。共通部は engine の agents-pack/AGENTS.core.md、"
        "ゲーム固有部は AGENTS.local.md を編集して再 sync -->",
        "",
    ]
    core = read_text_lf(ROOT / "agents-pack" / "AGENTS.core.md")
    parts.append(core.rstrip("\n"))
    parts.append("")
    parts.append("## 配られているスキル一覧（sync-agents が自動生成。手で編集しない）")
    parts.append("")
    for d in sorted(p for p in SKILLS_DIR.iterdir() if p.is_dir()):
        desc = skill_description(d / "SKILL.md")
        parts.append(f"- `.claude/skills/{d.name}/SKILL.md` — {desc}")
    local = game / "AGENTS.local.md"
    if local.is_file():
        parts.append("")
        parts.append(read_text_lf(local).rstrip("\n"))
    return "\n".join(parts) + "\n"


def copy_file(src, dst):
    dst.parent.mkdir(parents=True, exist_ok=True)
    # shutil.copy は実行ビットも写す (checkd / pre-commit はそのまま実行できる形で配る)
    shutil.copy(src, dst)


def copy_dir(src, dst):
    # copytree(dirs_exist_ok=) は古い Python に無いので自前で上書き重ね書きする
    for p in src.rglob("*"):
        rel = p.relative_to(src)
        if p.is_dir():
            (dst / rel).mkdir(parents=True, exist_ok=True)
        else:
            copy_file(p, dst / rel)


def sync(game, version):
    if not game.is_dir():
        print(f"error: ゲームのフォルダが見つかりません: {game}", file=sys.stderr)
        return 1
    m = load_manifest()

    write_text_lf(game / "AGENTS.md", build_agents_md(game, version))
    write_text_lf(game / "CLAUDE.md", "@AGENTS.md\n")

    for e in m["copyDirs"]:
        src, dst = ROOT / e["src"], game / e["dst"]
        dst.mkdir(parents=True, exist_ok=True)
        copy_dir(src, dst)
    for d in sorted(p for p in SKILLS_DIR.iterdir() if p.is_dir()):
        print(f"[sync-agents] skill: {d.name}")

    for e in m["copy"]:
        copy_file(ROOT / e["src"], game / e["dst"])

    for e in m["copyIfAbsent"]:
        dst = game / e["dst"]
        if not dst.exists():
            copy_file(ROOT / e["src"], dst)
            print(f"[sync-agents] hooks: {e['dst']} を配りました (既存があるときは上書きしない)")

    rules = " ".join(sorted(p.name for p in (ROOT / "agents-pack" / "rules").iterdir()))
    print(f"[sync-agents] rules: {rules}")
    lints = " ".join(e["dst"] for e in m["copy"]
                     if Path(e["dst"]).name.startswith("lint-"))
    print(f"[sync-agents] lint: {lints}")
    print("[sync-agents] checkd: bin/checkd + .claude/hooks/after-flix-edit.py")
    print("[sync-agents] 関所: bin/precommit.py + bin/githooks/pre-commit (配線は make hooks)")
    print(f"[sync-agents] wrote {game}/AGENTS.md + CLAUDE.md")
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--game")
    ap.add_argument("--version", default="unknown")
    ap.add_argument("--check-manifest", action="store_true")
    args = ap.parse_args()
    if args.check_manifest:
        return check_manifest()
    if not args.game:
        print("error: GAME を指定してください (make sync-agents GAME=/path/to/game)",
              file=sys.stderr)
        return 1
    return sync(Path(args.game), args.version)


if __name__ == "__main__":
    sys.exit(main())
