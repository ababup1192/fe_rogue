func TestCIEDE2000Sharma(t *testing.T) {
	if len(sharmaPairs) != 34 {
		t.Fatalf("参照データは 34 組のはず: %d", len(sharmaPairs))
	}
	worst := 0.0
	for i, c := range sharmaPairs {
		got := DeltaELab(c.a, c.b)
		d := math.Abs(got - c.want)
		if d > worst {
			worst = d
		}
		if d > 1e-4 {
			t.Errorf("%d 組目: %v vs %v = %.6f (期待 %.4f)", i+1, c.a, c.b, got, c.want)
		}
	}
	t.Logf("34 組の最大誤差 %.3e", worst)
}

func TestCIEDE2000Symmetry(t *testing.T) {
	for i, c := range sharmaPairs {
		if math.Abs(DeltaELab(c.a, c.b)-DeltaELab(c.b, c.a)) > 1e-9 {
			t.Errorf("%d 組目: 入れ替えると値が変わる", i+1)
		}
	}
}

func TestLabOfHexBlackWhite(t *testing.T) {
	if l := LabOfHex("#000000"); math.Abs(l[0]) > 1e-9 {
		t.Errorf("黒の L は 0 のはず: %v", l)
	}
	if l := LabOfHex("#ffffff"); math.Abs(l[0]-100) > 1e-3 {
		t.Errorf("白の L は 100 のはず: %v", l)
	}
}

func TestDeltaESameColorIsZero(t *testing.T) {
	if d := DeltaE("#1a2b3c", "#1a2b3c"); d != 0 {
		t.Errorf("同じ色の色差は 0 のはず: %v", d)
	}
}
